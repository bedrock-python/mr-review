#!/usr/bin/env node
// Writes src/app/styles/fonts.css from the installed @fontsource packages: woff2 only, the
// Latin, extended Latin and Cyrillic subsets, each with its unicode-range. Fontsource's own
// per-subset CSS files leave unicode-range out, which makes the browser download every subset
// of every face; its per-weight files carry woff fallbacks no supported browser needs.
//
// Run after bumping @fontsource/*: `node scripts/generate-fonts-css.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const FACES = [
  ["ibm-plex-sans", "400.css"],
  ["ibm-plex-sans", "400-italic.css"],
  ["ibm-plex-sans", "500.css"],
  ["ibm-plex-sans", "600.css"],
  ["jetbrains-mono", "400.css"],
  ["jetbrains-mono", "500.css"],
  ["jetbrains-mono", "600.css"],
];
const SUBSETS = ["latin", "latin-ext", "cyrillic"];
const BLOCK = /\/\* ([\w-]+) \*\/\s*@font-face \{([\s\S]*?)\}/g;

const out = [
  "/* Generated by scripts/generate-fonts-css.mjs from @fontsource — do not edit by hand.",
  "   One @font-face per family, weight and script, woff2 only. unicode-range makes the browser",
  "   fetch a file only when text in that script is on the page. */",
  "",
];
let count = 0;
for (const [family, cssName] of FACES) {
  const css = readFileSync(join(root, "node_modules/@fontsource", family, cssName), "utf8");
  for (const [, name, body] of css.matchAll(BLOCK)) {
    const isWanted = SUBSETS.some((subset) =>
      new RegExp(`-${subset}-\\d{3}-(normal|italic)$`).test(name)
    );
    if (!isWanted) continue;
    const pick = (re) => {
      const match = re.exec(body);
      if (!match) throw new Error(`${name}: ${re} not found`);
      return match[1];
    };
    out.push(
      `/* ${name} */`,
      "@font-face {",
      `  font-family: "${pick(/font-family: '([^']+)'/)}";`,
      `  font-style: ${pick(/font-style: (\w+)/)};`,
      "  font-display: swap;",
      `  font-weight: ${pick(/font-weight: (\d+)/)};`,
      `  src: url("../../../node_modules/@fontsource/${family}/files/${pick(/url\(\.\/files\/([\w.-]+\.woff2)\)/)}") format("woff2");`,
      `  unicode-range: ${pick(/unicode-range: ([^;]+);/)};`,
      "}",
      ""
    );
    count += 1;
  }
}
writeFileSync(join(root, "src/app/styles/fonts.css"), out.join("\n"));
console.log(`fonts.css: ${count} faces`);
